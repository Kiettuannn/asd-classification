        "        covs_np = np.asarray(covariances)\n"
        "\n"
        "    if device is None:\n"
        "        device = torch.device(\"cuda\" if torch.cuda.is_available() else \"cpu\")\n"
        "\n"
        "    covs = torch.from_numpy(covs_np).to(device=device, dtype=torch.float32)\n"
