        "        vals, vecs = torch.linalg.eigh(gmean)\n"
        "        inv_sqrt = (vecs * (1.0 / torch.sqrt(torch.clamp(vals, min=1e-6))).unsqueeze(-2)) @ vecs.transpose(-1, -2)\n"
