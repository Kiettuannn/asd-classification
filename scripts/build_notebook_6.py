        ") -> np.ndarray:\n"
        "    \"\"\"\n"
        "    Compute symmetric Riemannian Tangent Space Functional Connectivity matrices.\n"
        "    Reference Riemannian geometric mean covariance is fit strictly on training split subjects.\n"
        "    \"\"\"\n"
        "    if covariances is None:\n"
        "        if time_series_list is None:\n"
        "            raise ValueError(\"Either time_series_list or covariances must be provided.\")\n"
