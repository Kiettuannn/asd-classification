        "        w_vals, w_vecs = torch.linalg.eigh(whitened)\n"
        "        w_logs = (w_vecs * torch.log(torch.clamp(w_vals, min=1e-6)).unsqueeze(-2)) @ w_vecs.transpose(-1, -2)\n"
        "        logs_mean = torch.mean(w_logs, dim=0)\n"
        "        norm = torch.linalg.norm(logs_mean).item()\n"
        "\n"
        "        if norm / (p * p) < tol:\n"
        "            break\n"
        "\n"
        "        log_vals, log_vecs = torch.linalg.eigh(logs_mean)\n"
        "        sqrt_gmean = (vecs * torch.sqrt(torch.clamp(vals, min=1e-6)).unsqueeze(-2)) @ vecs.transpose(-1, -2)\n"
        "        step_mat = (log_vecs * torch.exp(log_vals * step).unsqueeze(-2)) @ log_vecs.transpose(-1, -2)\n"
        "        gmean = sqrt_gmean @ step_mat @ sqrt_gmean\n"
        "\n"
        "    vals, vecs = torch.linalg.eigh(gmean)\n"
        "    whitening = (vecs * (1.0 / torch.sqrt(torch.clamp(vals, min=1e-6))).unsqueeze(-2)) @ vecs.transpose(-1, -2)\n"
        "\n"
        "    whitened_all = whitening.unsqueeze(0) @ covs @ whitening.unsqueeze(0)\n"
        "    w_vals, w_vecs = torch.linalg.eigh(whitened_all)\n"
        "    tangent_matrices = (w_vecs * torch.log(torch.clamp(w_vals, min=1e-6)).unsqueeze(-2)) @ w_vecs.transpose(-1, -2)\n"
        "    tangent_matrices = 0.5 * (tangent_matrices + tangent_matrices.transpose(-1, -2))\n"
        "    return tangent_matrices.detach().cpu().numpy().astype(np.float32)\n"
        "\n"
        "\n"
        "def compute_dual_channel_fc(\n"
        "    covariances: np.ndarray,\n"
        "    fit_indices: Optional[Sequence[int]] = None,\n"
        "    device: Optional[torch.device] = None,\n"
        ") -> Tuple[np.ndarray, np.ndarray]:\n"
        "    \"\"\"\n"
        "    Compute Dual-Channel Functional Connectivity matrices and 400-D Node Features:\n"
        "      Channel 0: Riemannian Tangent Space FC.\n"
        "      Channel 1: Fisher z-transformed Pearson correlation with diagonal zeroed out.\n"
        "    Returns:\n"
        "      dual_matrices: np.ndarray of shape (N, 2, num_rois, num_rois)\n"
        "      node_features: np.ndarray of shape (N, num_rois, 400) combining tangent and Pearson profiles.\n"
        "    \"\"\"\n"
        "    tangent_matrices = compute_tangent_fc(covariances=covariances, fit_indices=fit_indices, device=device)\n"
        "    covs_np = np.asarray(covariances, dtype=np.float32)\n"
        "    n_total, p, _ = covs_np.shape\n"
        "\n"
        "    diag = np.diagonal(covs_np, axis1=-2, axis2=-1)\n"
        "    std = np.sqrt(np.clip(diag, a_min=1e-8, a_max=None))\n"
        "    std_inv = 1.0 / std\n"
        "    corr_matrices = covs_np * std_inv[..., None] * std_inv[..., None, :]\n"
        "    corr_matrices = 0.5 * (corr_matrices + np.swapaxes(corr_matrices, -1, -2))\n"
        "    corr_matrices = np.clip(corr_matrices, -0.9999, 0.9999)\n"
        "    z_corr = 0.5 * np.log((1.0 + corr_matrices) / (1.0 - corr_matrices))\n"
        "    z_corr = np.clip(z_corr, -3.0, 3.0)\n"
        "\n"
        "    eye_mask = np.eye(p, dtype=bool)\n"
        "    off_diag_mask = ~eye_mask\n"
        "\n"
        "    norm_tangent = tangent_matrices.copy()\n"
        "    norm_corr = z_corr.copy()\n"
        "\n"
        "    for i in range(n_total):\n"
        "        t_off = norm_tangent[i][off_diag_mask]\n"
        "        norm_tangent[i] = (norm_tangent[i] - t_off.mean()) / (t_off.std() + 1e-6)\n"
        "        norm_tangent[i][eye_mask] = 0.0\n"
        "\n"
        "        c_off = norm_corr[i][off_diag_mask]\n"
        "        norm_corr[i] = (norm_corr[i] - c_off.mean()) / (c_off.std() + 1e-6)\n"
        "        norm_corr[i][eye_mask] = 0.0\n"
        "\n"
        "    dual_matrices = np.stack([norm_tangent, norm_corr], axis=1).astype(np.float32)\n"
        "    # 400-dimensional whole-brain connectivity fingerprint per ROI node\n"
        "    node_features = np.concatenate([norm_tangent, norm_corr], axis=-1).astype(np.float32)\n"
        "    return dual_matrices, node_features"
