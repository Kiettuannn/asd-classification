            "    weight_decay: float = 1e-4,",
            ") -> Spatial3DCNNEncoder:",
            "    \"\"\"Pre-train 3D-CNN on static mean brain volumes for 10 fast epochs.\"\"\"",
            "    print('=' * 80)",
            "    print('PHASE 1: FAST STATIC 3D-CNN PRETRAINING ON TEMPORAL MEAN VOLUMES')",
            "    print('=' * 80)",
            "",
            "    # Filter manifest to subjects containing volumetric scans",
            "    vol_records = []",
            "    for _, r in manifest.iterrows():",
            "        fp = Path(r['file_path'])",
            "        if fp.suffix != '.pt':",
            "            vol_records.append(r)",
            "        else:",
            "            try:",
            "                meta = torch.load(fp, map_location='cpu', weights_only=True)",
            "                if 'volume' in meta:",
            "                    vol_records.append(r)",
            "            except Exception:",
            "                pass",
            "",
            "    if not vol_records:",
            "        print('[INFO] All discovered subjects are sequence-only features. Skipping 3D static pretraining.')",
