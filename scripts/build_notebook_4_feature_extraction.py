            "",
            "Extracts a 128-dimensional spatial embedding from 3D brain volumes via 4 volumetric blocks ($1 \\to 32 \\to 64 \\to 128 \\to 256$), Batch Normalization, LeakyReLU, and 3D Max Pooling.",
