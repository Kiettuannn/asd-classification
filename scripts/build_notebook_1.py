            "                        temp_dest.unlink()",
            "                    except OSError:",
            "                        pass",
            "                time.sleep(1.5 * attempt)",
            "",
            "    raise RuntimeError(f'Could not download fMRI scan for {file_id} from S3: {last_error}')",
            "",
            "",
            "def process_nyu_cohort(",
            "    manifest: pd.DataFrame,",
