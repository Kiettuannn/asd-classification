            "class EarlyStopping:",
            "    \"\"\"Early stopping monitor tracking validation metric and saving best checkpoint.\"\"\"",
            "    def __init__(",
            "        self,",
            "        patience: int = 25,",
            "        min_delta: float = 1e-4,",
            "        mode: str = 'max',",
            "        checkpoint_path: Optional[Union[str, Path]] = None,",
