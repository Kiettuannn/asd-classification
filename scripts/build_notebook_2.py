    cells.append(
        create_code_cell([
            "class EarlyStopping:",
            "    \"\"\"Early stopping monitor tracking validation loss.\"\"\"",
            "    def __init__(",
            "        self,",
            "        patience: int = 15,",
            "        min_delta: float = 1e-4,",
            "        mode: str = 'min',",
            "        checkpoint_path: Optional[Union[str, Path]] = None,",
            "    ) -> None:",
            "        self.patience = patience",
            "        self.min_delta = min_delta",
            "        self.mode = mode",
            "        self.checkpoint_path = Path(checkpoint_path) if checkpoint_path is not None else None",
            "        self.counter = 0",
            "        self.best_loss = float('inf')",
            "        self.early_stop = False",
            "",
            "    def __call__(self, val_loss: float, model: Optional[nn.Module] = None) -> bool:",
            "        if val_loss < (self.best_loss - self.min_delta):",
            "            self.best_loss = val_loss",
            "            self.counter = 0",
            "            if self.checkpoint_path is not None and model is not None:",
            "                self.checkpoint_path.parent.mkdir(parents=True, exist_ok=True)",
            "                if hasattr(model, 'save'):",
            "                    model.save(self.checkpoint_path)",
            "                else:",
            "                    torch.save(model.state_dict(), self.checkpoint_path)",
            "        else:",
            "            self.counter += 1",
            "            if self.counter >= self.patience:",
            "                self.early_stop = True",
            "        return self.early_stop",
            "",
            "",
            "def train_epoch(",
            "    model: nn.Module,",
            "    dataloader: DataLoader,",
            "    optimizer: torch.optim.Optimizer,",
            "    criterion: nn.Module,",
            "    scaler: Optional[torch.amp.GradScaler] = None,",
            "    accumulation_steps: int = 4,",
            "    device: torch.device = DEVICE,",
            ") -> float:",
            "    \"\"\"Run 1 train epoch with gradient accumulation and AMP.\"\"\"",
            "    model.train()",
            "    total_loss = 0.0",
            "    total_samples = 0",
            "    optimizer.zero_grad()",
            "    amp_active = (torch.device(device).type == 'cuda') and (scaler is not None)",
            "",
            "    for step, (inputs, targets) in enumerate(dataloader):",
            "        inputs = inputs.to(device, non_blocking=True)",
            "        targets = targets.to(device, non_blocking=True)",
            "        b_size = inputs.size(0)",
            "",
            "        if amp_active:",
            "            with torch.amp.autocast(device_type='cuda', dtype=torch.float16):",
            "                logits = model(inputs)",
            "                loss = criterion(logits, targets)",
            "                scaled_loss = loss / accumulation_steps",
            "            scaler.scale(scaled_loss).backward()",
            "        else:",
            "            logits = model(inputs)",
            "            loss = criterion(logits, targets)",
            "            scaled_loss = loss / accumulation_steps",
            "            scaled_loss.backward()",
            "",
            "        total_loss += loss.item() * b_size",
            "        total_samples += b_size",
            "",
            "        # Gradient accumulation step",
            "        if ((step + 1) % accumulation_steps == 0) or (step + 1 == len(dataloader)):",
            "            if amp_active and scaler is not None:",
            "                scaler.step(optimizer)",
            "                scaler.update()",
            "            else:",
            "                optimizer.step()",
            "            optimizer.zero_grad()",
            "",
            "    return total_loss / max(total_samples, 1)",
            "",
            "",
            "def evaluate_epoch(",
            "    model: nn.Module,",
            "    dataloader: DataLoader,",
            "    criterion: nn.Module,",
            "    device: torch.device = DEVICE,",
            ") -> Tuple[float, np.ndarray, np.ndarray, np.ndarray]:",
            "    \"\"\"Evaluate model on validation or test dataset without augmentation.\"\"\"",
            "    model.eval()",
            "    total_loss = 0.0",
            "    total_samples = 0",
            "    all_targets, all_preds, all_probs = [], [], []",
            "",
            "    with torch.no_grad():",
            "        for inputs, targets in dataloader:",
            "            inputs = inputs.to(device, non_blocking=True)",
            "            targets = targets.to(device, non_blocking=True)",
            "            b_size = inputs.size(0)",
            "",
            "            logits = model(inputs)",
            "            loss = criterion(logits, targets)",
            "            probs = torch.softmax(logits, dim=-1)",
            "            preds = torch.argmax(logits, dim=-1)",
            "",
            "            total_loss += loss.item() * b_size",
            "            total_samples += b_size",
            "",
            "            all_targets.append(targets.cpu().numpy())",
            "            all_preds.append(preds.cpu().numpy())",
            "            all_probs.append(probs.cpu().numpy())",
            "",
            "    y_true = np.concatenate(all_targets) if all_targets else np.array([])",
            "    y_pred = np.concatenate(all_preds) if all_preds else np.array([])",
            "    y_prob = np.concatenate(all_probs) if all_probs else np.empty((0, 2))",
            "    avg_loss = total_loss / max(total_samples, 1)",
            "    return avg_loss, y_true, y_pred, y_prob",
            "",
            "print('[INFO] Training and evaluation routines defined.')",
        ])
    )

