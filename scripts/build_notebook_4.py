            "        h1 = self.block1(chunk)",
            "        h2 = self.block2(h1)",
            "        h3 = self.block3(h2)",
            "        h4 = self.block4(h3)",
            "        pooled = self.global_pool(h4).flatten(1)",
            "        dropped = self.dropout(pooled)",
            "        return self.fc(dropped)",
