            "    \"\"\"Integrated Spatio-Temporal 3D-CNN with Bidirectional Mamba architecture.\"\"\"",
            "    def __init__(",
            "        self,",
            "        in_channels: int = 1,",
            "        d_model: int = 128,",
            "        d_state: int = 16,",
            "        d_conv: int = 4,",
            "        expand: int = 2,",
            "        num_layers: int = 2,",
            "        num_classes: int = 2,",
            "        spatial_dropout: float = 0.1,",
            "        temporal_dropout: float = 0.1,",
            "        attention_dropout: float = 0.0,",
            "        head_dropout: float = 0.4,",
            "        force_pure_pytorch: bool = False,",
            "        spatial_chunk_size: int = 16,",
            "        use_checkpoint: bool = True,",
            "    ) -> None:",
            "        super().__init__()",
            "        self.spatial_encoder = Spatial3DCNNEncoder(in_channels=in_channels, out_features=d_model, dropout=spatial_dropout, spatial_chunk_size=spatial_chunk_size, use_checkpoint=use_checkpoint)",
