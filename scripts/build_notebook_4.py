            "        if not file_path.exists():",
            "            raise FileNotFoundError(f'Feature file not found: {file_path}')",
            "",
            "        payload = torch.load(file_path, map_location='cpu', weights_only=True)",
            "        features = payload['features'] if 'features' in payload else payload['volume']",
            "        mask = payload.get('mask')",
            "",
            "        if features.dim() > 2:",
            "            features = features.squeeze()",
            "",
            "        if mask is None or features.shape[0] != self.target_seq_len:",
            "            features, mask = pad_temporal_sequence(features, target_length=self.target_seq_len)",
            "",
            "        return {",
            "            'volume': features.to(torch.float32),",
            "            'features': features.to(torch.float32),",
            "            'mask': mask.to(torch.bool),",
            "            'label': torch.tensor(int(payload.get('label', row['label'])), dtype=torch.long),",
            "            'subject_id': str(payload.get('subject_id', row.get('subject_id', idx))),",
            "            'site_id': str(payload.get('site_id', row.get('site_id', 'UNKNOWN'))),",
            "        }",
            "",
            "def spatiotemporal_collate_fn(batch: Sequence[Dict[str, Any]]) -> Dict[str, Any]:",
            "    \"\"\"Collate individual subject dictionaries into batched PyTorch tensors.\"\"\"",
