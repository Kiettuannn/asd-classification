            "    fold_results: List[Dict[str, Any]] = []",
            "    oof_targets: List[int] = []",
            "    oof_preds: List[int] = []",
            "    oof_probs: List[List[float]] = []",
            "    oof_attentions: List[np.ndarray] = []",
            "    oof_masks: List[np.ndarray] = []",
